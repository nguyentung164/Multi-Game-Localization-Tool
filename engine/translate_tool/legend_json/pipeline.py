def iter_root_array(path: Path, *, chunk_size: int = 1024 * 1024) -> Iterator[tuple[int, Any]]:
    """Đọc từng phần tử root array, chấp nhận control character trong JSON string."""

    decoder = json.JSONDecoder(strict=False)
    with path.open("rb") as binary:
        stream = io.TextIOWrapper(binary, encoding="utf-8-sig", errors="strict", newline="")
        buffer = ""
        cursor = 0
        eof = False

        def read_more() -> bool:
            nonlocal buffer, eof
            chunk = stream.read(chunk_size)
            if chunk:
                buffer += chunk
                return True
            eof = True
            return False

        def ensure_content() -> None:
            nonlocal cursor
            while True:
                while cursor < len(buffer) and buffer[cursor].isspace():
                    cursor += 1
                if cursor < len(buffer) or eof:
                    return
                read_more()

        ensure_content()
        if cursor >= len(buffer) or buffer[cursor] != "[":
            raise ValidationError(f"JSON phải có root array: {path.name}")
        cursor += 1
        index = 0
        expecting_value = True
        while True:
            ensure_content()
            if cursor >= len(buffer):
                raise ValidationError(f"JSON root array chưa đóng: {path.name}")
            if buffer[cursor] == "]":
                cursor += 1
                break
            if not expecting_value:
                if buffer[cursor] != ",":
                    raise ValidationError(f"JSON thiếu dấu phẩy gần record {index}: {path.name}")
                cursor += 1
                ensure_content()
            while True:
                try:
                    value, end = decoder.raw_decode(buffer, cursor)
                    break
                except json.JSONDecodeError as error:
                    if eof:
                        raise ValidationError(
                            f"JSON lỗi gần record {index} ({error.msg}): {path.name}"
                        ) from error
                    read_more()
            yield index, value
            index += 1
            cursor = end
            expecting_value = False
            if cursor > chunk_size * 2:
                buffer = buffer[cursor:]
                cursor = 0

        while True:
            while cursor < len(buffer) and buffer[cursor].isspace():
                cursor += 1
            if cursor < len(buffer):
                raise ValidationError(f"JSON có dữ liệu sau root array: {path.name}")
            if eof or not read_more():
                break


