def _json_pointer(parts: Sequence[str | int]) -> str:
    encoded = [str(part).replace("~", "~0").replace("/", "~1") for part in parts]
    return "/" + "/".join(encoded)


def _default_field_action(field: str) -> str:
    if TECHNICAL_FIELD_RE.match(field) or LANGUAGE_SUFFIX_RE.search(field):
        return "exclude"
    if field in ALLOW_FIELDS:
        return "allow"
    if field in COMPOSITE_FIELDS or PHASE_EFFECT_RE.match(field):
        return "composite"
    return "classify"


def _rule_action(rules: Sequence[PipelineRule], file_name: str, field: str) -> str:
    action = _default_field_action(field)
    for rule in rules:
        if rule.field == field and fnmatch.fnmatch(file_name, rule.file_pattern):
            action = rule.action
    return action


def _plain_composite_text(text: str) -> tuple[list[str], bool]:
    if not has_han(text):
        return [], True
    if any(token in text for token in ("/", ";", "@", "&&", "&#&")):
        return [], False
    return [text], True


def _option_segments(text: str) -> tuple[list[str], bool]:
    if "&" not in text and "#" not in text:
        return _plain_composite_text(text)
    segments: list[str] = []
    chunks = text.split("#")
    for chunk in chunks:
        before_controls, separator, controls = chunk.partition("&&")
        candidates = [
            field.strip()
            for field in before_controls.strip("& ").split("&")
            if has_han(field.strip())
        ]
        if not candidates:
            if has_han(chunk):
                return [], False
            continue
        if separator and has_han(controls):
            return [], False
        segments.append(candidates[-1])
    return segments, bool(segments) or not has_han(text)


def _box_segments(text: str) -> tuple[list[str], bool]:
    segments: list[str] = []
    records = [record for record in text.split(";") if record.strip()]
    if not records:
        return _plain_composite_text(text)
    for record in records:
        fields = record.split("/")
        if len(fields) < 5:
            return [], False
        try:
            for coordinate in fields[:4]:
                float(coordinate)
        except ValueError:
            return [], False
        display_fields = [field.strip() for field in fields[4:] if field.strip()]
        if not display_fields or any(not has_han(field) for field in display_fields):
            return [], False
        segments.extend(display_fields)
    return segments, bool(segments)


def _record_composite_segments(field: str, text: str) -> tuple[list[str], bool]:
    layouts = {
        "specialNI": (3, (0, 1), 2, ()),
        "specialWO": (2, (0,), 1, ()),
        "zuncheng": (4, (0,), 1, (2, 3)),
    }
    field_count, id_indexes, display_index, numeric_indexes = layouts[field]
    segments: list[str] = []
    records = [record for record in text.split(";") if record.strip()]
    if not records:
        return _plain_composite_text(text)
    for record in records:
        body = record.removesuffix("@@@@@").strip()
        fields = body.split("/")
        if len(fields) != field_count:
            return [], False
        if any(not re.fullmatch(r"WJ\d+", fields[index]) for index in id_indexes):
            return [], False
        if any(not re.fullmatch(r"-?\d+", fields[index]) for index in numeric_indexes):
            return [], False
        candidate = fields[display_index].strip()
        if not candidate or not has_han(candidate):
            return [], False
        segments.append(candidate)
    return segments, bool(segments)


def _composite_segments(field: str, text: str) -> tuple[list[str], bool]:
    if field == "option":
        return _option_segments(text)
    if field == "box":
        return _box_segments(text)
    if field == "aryEffectStr":
        if "@@@@@" not in text:
            return _plain_composite_text(text)
        chunks = text.split("@@@@@")
        segments = [chunk.strip("& ;") for chunk in chunks if chunk.strip("& ;")]
        if any(not has_han(segment) for segment in segments):
            return [], False
        return segments, bool(segments) or not has_han(text)
    if PHASE_EFFECT_RE.match(field):
        return ([text] if has_han(text) else []), True
    if field in {"specialNI", "specialWO", "zuncheng"}:
        return _record_composite_segments(field, text)
    return [], False


def extract_record(
    record: Any,
    *,
    file_name: str,
    record_index: int,
    rules: Sequence[PipelineRule] = (),
    text_actions: Mapping[str, str] | None = None,
) -> list[ExtractedOccurrence]:
    result: list[ExtractedOccurrence] = []
    text_actions = text_actions or {}
    record_id: str | None = None
    if isinstance(record, Mapping):
        for candidate in RECORD_ID_FIELDS:
            if candidate in record and record[candidate] not in (None, ""):
                record_id = str(record[candidate])
                break

    def walk(value: Any, parts: list[str | int]) -> None:
        if isinstance(value, Mapping):
            for key, child in value.items():
                walk(child, [*parts, str(key)])
            return
        if isinstance(value, list):
            for child_index, child in enumerate(value):
                walk(child, [*parts, child_index])
            return
        if not isinstance(value, str) or not value.strip() or not has_han(value):
            return
        field = str(parts[-1]) if parts else ""
        text_action = text_actions.get(_text_hash(value))
        action = text_action or _rule_action(rules, file_name, field)
        is_composite_field = _default_field_action(field) == "composite"
        if action == "composite" or (
            is_composite_field and action == "allow" and text_action is None
        ):
            segments, recognized = _composite_segments(field, value)
            if not recognized:
                result.append(
                    ExtractedOccurrence(
                        value,
                        _json_pointer(parts),
                        field,
                        record_id,
                        "composite-unrecognized",
                        "classify",
                        value[:500],
                    )
                )
                return
            for segment_index, segment in enumerate(segments):
                classification = text_actions.get(_text_hash(segment), "allow")
                result.append(
                    ExtractedOccurrence(
                        segment,
                        f"{_json_pointer(parts)}#display/{segment_index}",
                        field,
                        record_id,
                        f"composite:{field}",
                        classification,
                        value[:500],
                    )
                )
            return
        result.append(
            ExtractedOccurrence(
                value,
                _json_pointer(parts),
                field,
                record_id,
                "field",
                action,
                value[:500],
            )
        )

    walk(record, [record_index])
    return result


def _connect(db_path: Path) -> sqlite3.Connection:
    if not db_path.is_absolute() or "\x00" in str(db_path):
        raise ValidationError("dbPath phải là đường dẫn tuyệt đối")
    db_path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(db_path, timeout=60)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA journal_mode = WAL")
    connection.execute("PRAGMA synchronous = NORMAL")
    _initialize_schema(connection)
    return connection


