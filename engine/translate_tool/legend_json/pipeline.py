def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def _text_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _canonical_hash(value: Any) -> str:
    return _text_hash(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")))


def _absolute_directory(path: Path, label: str) -> Path:
    if not path.is_absolute() or "\x00" in str(path):
        raise ValidationError(f"{label} phải là đường dẫn tuyệt đối hợp lệ")
    try:
        resolved = path.resolve(strict=True)
    except OSError as error:
        raise ValidationError(f"Không mở được {label}: {error}") from error
    if not resolved.is_dir():
        raise ValidationError(f"{label} không phải thư mục")
    return resolved


def _absolute_file(path: Path, label: str, *, must_exist: bool = True) -> Path:
    if not path.is_absolute() or "\x00" in str(path):
        raise ValidationError(f"{label} phải là đường dẫn tuyệt đối hợp lệ")
    resolved = path.resolve(strict=False)
    if must_exist and not resolved.is_file():
        raise ValidationError(f"Không tìm thấy {label}")
    if not must_exist and not resolved.parent.is_dir():
        raise ValidationError(f"Thư mục chứa {label} không tồn tại")
    return resolved


